"""Logging estructurado en JSON (una línea por evento, listo para ingestar en
Loki/CloudWatch/Datadog). Ver ARQUITECTURA.md §8."""

import json
import logging
import sys
import time

# Atributos propios de LogRecord que no son "extras" del llamador.
_RESERVED = {
    "name", "msg", "args", "levelname", "levelno", "pathname", "filename",
    "module", "exc_info", "exc_text", "stack_info", "lineno", "funcName",
    "created", "msecs", "relativeCreated", "thread", "threadName",
    "processName", "process", "taskName", "message", "asctime",
}


class JsonFormatter(logging.Formatter):
    def format(self, record: logging.LogRecord) -> str:
        payload: dict = {
            "ts": time.strftime("%Y-%m-%dT%H:%M:%S", time.gmtime(record.created)),
            "level": record.levelname,
            "logger": record.name,
            "message": record.getMessage(),
        }
        for key, value in record.__dict__.items():
            if key not in _RESERVED and not key.startswith("_"):
                payload[key] = value
        if record.exc_info:
            payload["exc_info"] = self.formatException(record.exc_info)
        return json.dumps(payload, ensure_ascii=False, default=str)


def setup_logging(level: str = "INFO") -> None:
    handler = logging.StreamHandler(sys.stdout)
    handler.setFormatter(JsonFormatter())

    root = logging.getLogger()
    root.handlers = [handler]
    root.setLevel(level.upper())

    # Librerías ruidosas que no aportan a la demo.
    for noisy in ("httpx", "httpcore", "chromadb", "sentence_transformers",
                  "transformers", "urllib3", "openai"):
        logging.getLogger(noisy).setLevel(logging.WARNING)
